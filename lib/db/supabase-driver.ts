/**
 * Supabase driver — talks to the PostgREST API with plain fetch (no SDK).
 *
 * Active when SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY are set.
 * The service-role key bypasses Row Level Security, so it must stay
 * server-side (never prefix it with NEXT_PUBLIC_). Create the tables by
 * running supabase/schema.sql in the Supabase SQL editor.
 */
import type { Driver, Row, TableName } from './types';

const base = () => `${process.env.SUPABASE_URL!.replace(/\/$/, '')}/rest/v1`;

const headers = (extra?: Record<string, string>) => ({
  apikey: process.env.SUPABASE_SERVICE_ROLE_KEY!,
  Authorization: `Bearer ${process.env.SUPABASE_SERVICE_ROLE_KEY!}`,
  'Content-Type': 'application/json',
  ...extra,
});

const filters = (where: Row) =>
  Object.entries(where).map(([k, v]) =>
    v === null ? `${encodeURIComponent(k)}=is.null` : `${encodeURIComponent(k)}=eq.${encodeURIComponent(String(v))}`,
  );

async function call(url: string, init: RequestInit): Promise<Response> {
  const res = await fetch(url, { ...init, cache: 'no-store' });
  if (!res.ok) throw new Error(`Supabase ${res.status}: ${(await res.text()).slice(0, 300)}`);
  return res;
}

export const supabaseDriver: Driver = {
  name: 'supabase',

  async select(table: TableName, where) {
    const qs = ['select=*', ...(where ? filters(where) : [])].join('&');
    return (await call(`${base()}/${table}?${qs}`, { headers: headers() })).json() as Promise<Row[]>;
  },

  async selectIn(table, field, values) {
    // ids are generated by us, but never trust a value that ends up in a URL
    const safe = values.filter((v) => /^[\w-]+$/.test(v));
    if (!safe.length) return [];
    const qs = `select=*&${encodeURIComponent(field)}=in.(${safe.join(',')})`;
    return (await call(`${base()}/${table}?${qs}`, { headers: headers() })).json() as Promise<Row[]>;
  },

  async insert(table, row) {
    await call(`${base()}/${table}`, {
      method: 'POST',
      headers: headers({ Prefer: 'return=minimal' }),
      body: JSON.stringify(row),
    });
  },

  async update(table, id, patch) {
    const res = await call(`${base()}/${table}?id=eq.${encodeURIComponent(id)}`, {
      method: 'PATCH',
      headers: headers({ Prefer: 'return=representation' }),
      body: JSON.stringify(patch),
    });
    return ((await res.json()) as Row[]).length > 0;
  },

  async remove(table, where) {
    if (!Object.keys(where).length) throw new Error('remove() needs a filter');
    await call(`${base()}/${table}?${filters(where).join('&')}`, { method: 'DELETE', headers: headers() });
  },
};
